#!/usr/bin/env bash
set -Eeuo pipefail

mode="check"
config_path="/etc/V2bX/hy2config.yaml"
service_name="V2bX"
skip_restart=0

usage() {
    cat <<'EOF'
Usage: fix-legacy-hy2-config.sh [check | apply] [options]

Removes only the exact three-rule native-Hysteria2 ACL generated by the old
wyx2685/V2bX installer:
  direct(geosite:google)
  reject(geosite:cn)
  reject(geoip:cn)

The default check is read-only. Customized, duplicated, reordered, or partial
ACLs are rejected instead of being guessed.

Options:
  --config PATH    Hysteria2 YAML path (default: /etc/V2bX/hy2config.yaml)
  --service NAME   Service name (default: V2bX)
  --skip-restart   Do not restart an already-active service
  -h, --help       Show this help
EOF
}

while (($# > 0)); do
    case "$1" in
        check|--check)
            mode="check"
            shift
            ;;
        apply|--apply)
            mode="apply"
            shift
            ;;
        --config)
            [[ $# -ge 2 ]] || { echo "ERROR: --config requires a path" >&2; exit 2; }
            config_path="$2"
            shift 2
            ;;
        --service)
            [[ $# -ge 2 ]] || { echo "ERROR: --service requires a name" >&2; exit 2; }
            service_name="$2"
            shift 2
            ;;
        --skip-restart)
            skip_restart=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "ERROR: unknown argument: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

[[ -f "$config_path" && ! -L "$config_path" ]] || {
    echo "ERROR: expected a regular non-symlink config: $config_path" >&2
    exit 1
}

if [[ "$mode" == "apply" && "${V2BX_FIX_SKIP_ROOT_CHECK:-0}" != "1" && "$(id -u)" -ne 0 ]]; then
    echo "ERROR: apply must run as root" >&2
    exit 1
fi

count_exact() {
    local expected="$1"
    awk -v expected="$expected" '
        {
            line = $0
            sub(/\r$/, "", line)
            sub(/^[ \t]*-[ \t]*/, "", line)
            sub(/[ \t]+(#.*)?$/, "", line)
            if (line == expected) count++
        }
        END { print count + 0 }
    ' "$config_path"
}

line_of_exact() {
    local expected="$1"
    awk -v expected="$expected" '
        {
            line = $0
            sub(/\r$/, "", line)
            sub(/^[ \t]*-[ \t]*/, "", line)
            sub(/[ \t]+(#.*)?$/, "", line)
            if (line == expected) { print NR; exit }
        }
    ' "$config_path"
}

google_count=$(count_exact 'direct(geosite:google)')
geosite_count=$(count_exact 'reject(geosite:cn)')
geoip_count=$(count_exact 'reject(geoip:cn)')

if ((google_count == 0 && geosite_count == 0 && geoip_count == 0)); then
    echo "OK: legacy native-Hysteria2 China ACL is absent"
    exit 0
fi
if ((google_count != 1 || geosite_count != 1 || geoip_count != 1)); then
    echo "ERROR: legacy ACL is partial or duplicated ($google_count/$geosite_count/$geoip_count); no change made" >&2
    exit 1
fi

google_line=$(line_of_exact 'direct(geosite:google)')
geosite_line=$(line_of_exact 'reject(geosite:cn)')
geoip_line=$(line_of_exact 'reject(geoip:cn)')
if ((geosite_line != google_line + 1 || geoip_line != geosite_line + 1)); then
    echo "ERROR: legacy ACL rules are not the exact consecutive installer block; no change made" >&2
    exit 1
fi

acl_line=$(awk -v target="$google_line" '
    NR < target {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /^acl:[ \t]*(#.*)?$/) found = NR
    }
    END { if (found) print found }
' "$config_path")
[[ -n "$acl_line" ]] || { echo "ERROR: rule block is not inside a top-level acl section" >&2; exit 1; }

section_end=$(awk -v start="$acl_line" '
    NR > start {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /^[^ \t#][^:]*:[ \t]*(#.*)?$/) { print NR; exit }
    }
' "$config_path")
[[ -n "$section_end" ]] || section_end=$(( $(wc -l < "$config_path") + 1 ))
((geoip_line < section_end)) || { echo "ERROR: rule block falls outside acl" >&2; exit 1; }

inline_line=$(awk -v start="$acl_line" -v end="$google_line" '
    NR > start && NR < end {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /^[ \t]+inline:[ \t]*(#.*)?$/) { print NR; exit }
    }
' "$config_path")
[[ -n "$inline_line" ]] || { echo "ERROR: rule block is not inside acl.inline" >&2; exit 1; }

if [[ "$mode" == "check" ]]; then
    echo "NEEDS APPLY: exact legacy native-Hysteria2 China ACL found at lines $google_line-$geoip_line"
    exit 3
fi

config_dir=$(dirname "$config_path")
backup_path="${config_path}.before-cn-acl-fix.$(date -u +%Y%m%dT%H%M%SZ)"
stage_path=""
render_path=""
fallback_lock=""
service_was_active=0
changed=0

cleanup() {
    [[ -n "$stage_path" ]] && rm -f -- "$stage_path" 2>/dev/null || true
    [[ -n "$render_path" ]] && rm -f -- "$render_path" 2>/dev/null || true
    [[ -n "$fallback_lock" ]] && rmdir -- "$fallback_lock" 2>/dev/null || true
}
trap cleanup EXIT

if command -v flock >/dev/null 2>&1; then
    exec 9>"${config_path}.v2bx-fix.lock"
    flock -n 9 || { echo "ERROR: another Hy2 config operation is active" >&2; exit 1; }
else
    fallback_lock="${config_path}.v2bx-fix.lock.d"
    mkdir -- "$fallback_lock" 2>/dev/null || { echo "ERROR: another Hy2 config operation may be active" >&2; exit 1; }
fi

if command -v systemctl >/dev/null 2>&1 && systemctl is-active --quiet "$service_name"; then
    service_was_active=1
elif command -v rc-service >/dev/null 2>&1 && rc-service "$service_name" status >/dev/null 2>&1; then
    service_was_active=1
fi

cp -a -- "$config_path" "$backup_path"
stage_path=$(mktemp "$config_dir/.hy2config.fix.XXXXXX")
cp -a -- "$config_path" "$stage_path"
render_path=$(mktemp "$config_dir/.hy2config.render.XXXXXX")

# Remove the exact generated rules. If the ACL section contains nothing else,
# remove the now-empty acl section too; customized ACL entries are preserved.
other_acl_content=$(awk -v start="$acl_line" -v end="$section_end" \
    -v google="$google_line" -v geosite="$geosite_line" -v geoip="$geoip_line" '
    NR > start && NR < end && NR != google && NR != geosite && NR != geoip {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /^[ \t]*$/ || line ~ /^[ \t]*#/ || line ~ /^[ \t]+inline:[ \t]*(#.*)?$/) next
        count++
    }
    END { print count + 0 }
' "$config_path")

if ((other_acl_content == 0)); then
    awk -v start="$acl_line" -v end="$section_end" 'NR < start || NR >= end' "$stage_path" > "$render_path"
else
    awk -v first="$google_line" -v last="$geoip_line" 'NR < first || NR > last' "$stage_path" > "$render_path"
fi
cat "$render_path" > "$stage_path"

if count_after=$(awk '
    {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /reject\((geosite|geoip):cn\)/) count++
    }
    END { print count + 0 }
' "$stage_path") && ((count_after != 0)); then
    echo "ERROR: staged config still contains a China reject rule" >&2
    exit 1
fi

rollback() {
    local status="$1"
    trap - ERR INT TERM
    set +e
    if ((changed)); then
        cp -a -- "$backup_path" "$config_path"
        if ((service_was_active && !skip_restart)); then
            if command -v systemctl >/dev/null 2>&1; then
                systemctl restart "$service_name"
            else
                rc-service "$service_name" restart
            fi
        fi
    fi
    echo "ERROR: apply failed; restored $backup_path" >&2
    exit "$status"
}

trap 'rollback $?' ERR
trap 'rollback 130' INT
trap 'rollback 143' TERM
changed=1
mv -f -- "$stage_path" "$config_path"
stage_path=""

if ((service_was_active && !skip_restart)); then
    if command -v systemctl >/dev/null 2>&1; then
        systemctl restart "$service_name"
        systemctl is-active --quiet "$service_name"
    else
        rc-service "$service_name" restart
        rc-service "$service_name" status >/dev/null
    fi
fi

changed=0
trap - ERR INT TERM
echo "APPLIED: removed only the exact legacy native-Hysteria2 China ACL"
echo "BACKUP: $backup_path"
