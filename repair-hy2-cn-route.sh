#!/usr/bin/env bash
set -Eeuo pipefail

config_path="/etc/V2bX/hy2config.yaml"
service_name="V2bX"
mode="check"
skip_restart=0

usage() {
    cat <<'EOF'
Usage: repair-hy2-cn-route.sh [--check | --apply] [options]

Adds explicit Bilibili domain exceptions immediately before the exact legacy
reject(geosite:cn) / reject(geoip:cn) pair generated by wyx2685/V2bX-script.
The China reject rules remain enabled, so unrelated China destinations stay
blocked. The default --check mode is read-only.

Options:
  --config PATH    Hysteria2 YAML path (default: /etc/V2bX/hy2config.yaml)
  --service NAME   V2bX service name (default: V2bX)
  --skip-restart   Keep the current service state and validate manually
  -h, --help       Show this help

--apply uses a lock, creates a metadata-preserving backup, replaces the file
atomically, restarts V2bX only when it was already active, and rolls back on
write, signal, restart, or health-check failure.
EOF
}

while (($# > 0)); do
    case "$1" in
        --check)
            mode="check"
            shift
            ;;
        --apply)
            mode="apply"
            shift
            ;;
        --config)
            [[ $# -ge 2 ]] || { echo "ERROR: --config requires a path" >&2; exit 2; }
            config_path="$2"
            shift 2
            ;;
        --service)
            [[ $# -ge 2 ]] || { echo "ERROR: --service requires a name" >&2; exit 2; }
            service_name="$2"
            shift 2
            ;;
        --skip-restart)
            skip_restart=1
            shift
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "ERROR: unknown argument: $1" >&2
            usage >&2
            exit 2
            ;;
    esac
done

[[ -f "$config_path" ]] || { echo "ERROR: config not found: $config_path" >&2; exit 1; }
[[ -r "$config_path" ]] || { echo "ERROR: config is not readable: $config_path" >&2; exit 1; }

if command -v readlink >/dev/null 2>&1; then
    resolved_path=$(readlink -f -- "$config_path" 2>/dev/null || true)
    if [[ -n "$resolved_path" ]]; then
        config_path="$resolved_path"
    fi
fi

if [[ "$mode" == "apply" && "${V2BX_REPAIR_SKIP_ROOT_CHECK:-0}" != "1" && "$(id -u)" -ne 0 ]]; then
    echo "ERROR: --apply must run as root" >&2
    exit 1
fi

config_dir=$(dirname "$config_path")
temp_dir=""
stage_dir=""
fallback_lock_dir=""

cleanup() {
    if [[ -n "$stage_dir" && -d "$stage_dir" ]]; then
        rm -rf -- "$stage_dir"
    fi
    if [[ -n "$temp_dir" && -d "$temp_dir" ]]; then
        rm -rf -- "$temp_dir"
    fi
    if [[ -n "$fallback_lock_dir" && -d "$fallback_lock_dir" ]]; then
        rmdir -- "$fallback_lock_dir" 2>/dev/null || true
    fi
}
trap cleanup EXIT

if [[ "$mode" == "apply" ]]; then
    lock_path="${config_path}.codex-bilibili-repair.lock"
    if command -v flock >/dev/null 2>&1; then
        exec 9>"$lock_path"
        if ! flock -n 9; then
            echo "ERROR: another repair process holds $lock_path" >&2
            exit 1
        fi
    else
        fallback_lock_dir="${lock_path}.d"
        if ! mkdir -- "$fallback_lock_dir" 2>/dev/null; then
            echo "ERROR: another repair process may be active: $fallback_lock_dir" >&2
            exit 1
        fi
    fi
fi

count_matches() {
    local pattern="$1" path="$2" count status
    set +e
    count=$(grep -Ec -- "$pattern" "$path")
    status=$?
    set -e
    if ((status > 1)); then
        echo "ERROR: failed to inspect $path" >&2
        return "$status"
    fi
    printf '%s\n' "${count:-0}"
}

geosite_pattern='^[[:space:]]*-[[:space:]]*reject\(geosite:cn\)[[:space:]]*(#.*)?$'
geoip_pattern='^[[:space:]]*-[[:space:]]*reject\(geoip:cn\)[[:space:]]*(#.*)?$'
managed_begin_pattern='^[[:space:]]*#[[:space:]]*codex-bilibili-cn-exception-begin[[:space:]]*$'
managed_end_pattern='^[[:space:]]*#[[:space:]]*codex-bilibili-cn-exception-end[[:space:]]*$'
geosite_count=$(count_matches "$geosite_pattern" "$config_path")
geoip_count=$(count_matches "$geoip_pattern" "$config_path")

if ((geosite_count == 0 && geoip_count == 0)); then
    echo "NO CHANGE: the China reject pair is absent; this script will not add it"
    exit 0
fi

if ((geosite_count != 1 || geoip_count != 1)); then
    echo "ERROR: expected exactly one generated geosite:cn/geoip:cn pair; found $geosite_count/$geoip_count" >&2
    echo "No file was changed because the ACL appears customized or incomplete." >&2
    exit 1
fi

geosite_line=$(grep -En -- "$geosite_pattern" "$config_path" | cut -d: -f1)
geoip_line=$(grep -En -- "$geoip_pattern" "$config_path" | cut -d: -f1)
if ((geoip_line != geosite_line + 1)); then
    echo "ERROR: the China reject entries are not the consecutive pair generated by V2bX-script" >&2
    echo "No file was changed." >&2
    exit 1
fi

acl_line=$(awk -v target="$geosite_line" 'NR < target && /^acl:[[:space:]]*(#.*)?$/ { line = NR } END { if (line) print line }' "$config_path")
if [[ -z "$acl_line" ]]; then
    echo "ERROR: the generated China reject pair is not inside a top-level acl section" >&2
    exit 1
fi

section_end=$(awk -v start="$acl_line" 'NR > start && /^[^[:space:]#][^:]*:[[:space:]]*/ { print NR; exit }' "$config_path")
if [[ -z "$section_end" ]]; then
    section_end=$(( $(wc -l < "$config_path") + 1 ))
fi
if ((geosite_line >= section_end)); then
    echo "ERROR: the China reject pair is outside the detected acl section" >&2
    exit 1
fi

inline_line=$(awk -v start="$acl_line" -v end="$section_end" '
    NR > start && NR < end && /^[[:space:]]+inline:[[:space:]]*(#.*)?$/ { print NR; exit }
' "$config_path")
if [[ -z "$inline_line" || "$inline_line" -ge "$geosite_line" ]]; then
    echo "ERROR: the China reject pair is not inside acl.inline" >&2
    exit 1
fi

inline_indent=$(awk -v line="$inline_line" 'NR == line { match($0, /^[ \t]*/); print RLENGTH }' "$config_path")
geosite_indent=$(awk -v line="$geosite_line" 'NR == line { match($0, /^[ \t]*/); print RLENGTH }' "$config_path")
geoip_indent=$(awk -v line="$geoip_line" 'NR == line { match($0, /^[ \t]*/); print RLENGTH }' "$config_path")
if ((geosite_indent <= inline_indent || geoip_indent != geosite_indent)); then
    echo "ERROR: the China reject pair does not have the generated acl.inline indentation" >&2
    exit 1
fi

inline_break_line=$(awk -v start="$inline_line" -v target="$geosite_line" -v max_indent="$inline_indent" '
    NR > start && NR < target {
        line = $0
        sub(/\r$/, "", line)
        if (line ~ /^[ \t]*($|#)/) next
        match(line, /^[ \t]*/)
        if (RLENGTH <= max_indent) {
            print NR
            exit
        }
    }
' "$config_path")
if [[ -n "$inline_break_line" ]]; then
    echo "ERROR: acl.inline ends before the China reject pair (line $inline_break_line)" >&2
    exit 1
fi

managed_begin_count=$(count_matches "$managed_begin_pattern" "$config_path")
managed_end_count=$(count_matches "$managed_end_pattern" "$config_path")
if ((managed_begin_count != managed_end_count || managed_begin_count > 1)); then
    echo "ERROR: the managed Bilibili block markers are incomplete or duplicated" >&2
    echo "No file was changed." >&2
    exit 1
fi

managed_begin_line=0
managed_end_line=0
if ((managed_begin_count == 1)); then
    managed_begin_line=$(grep -En -- "$managed_begin_pattern" "$config_path" | cut -d: -f1)
    managed_end_line=$(grep -En -- "$managed_end_pattern" "$config_path" | cut -d: -f1)
    managed_begin_indent=$(awk -v line="$managed_begin_line" 'NR == line { match($0, /^[ \t]*/); print RLENGTH }' "$config_path")
    managed_end_indent=$(awk -v line="$managed_end_line" 'NR == line { match($0, /^[ \t]*/); print RLENGTH }' "$config_path")
    if ((managed_begin_line >= managed_end_line || managed_begin_line <= inline_line ||
         managed_end_line >= geosite_line || managed_begin_indent != geosite_indent ||
         managed_end_indent != geosite_indent)); then
        echo "ERROR: the managed Bilibili block is outside the expected acl.inline position" >&2
        echo "No file was changed." >&2
        exit 1
    fi
fi

temp_dir=$(mktemp -d)
candidate_path="$temp_dir/hy2config.yaml"
rules_path="$temp_dir/bilibili-rules.txt"
bilibili_rules=(
    'direct(suffix:acg.tv)'
    'direct(suffix:acgvideo.com)'
    'direct(suffix:b23.tv)'
    'direct(suffix:bili22.cn)'
    'direct(suffix:bili2233.cn)'
    'direct(suffix:bili23.cn)'
    'direct(suffix:bili33.cn)'
    'direct(suffix:biliapi.com)'
    'direct(suffix:biliapi.net)'
    'direct(suffix:bilibili.cc)'
    'direct(suffix:bilibili.cn)'
    'direct(suffix:bilibili.com)'
    'direct(suffix:bilibili.net)'
    'direct(suffix:bilibili.tv)'
    'direct(suffix:bilicdn1.com)'
    'direct(suffix:bilicdn2.com)'
    'direct(suffix:bilicdn3.com)'
    'direct(suffix:bilicdn4.com)'
    'direct(suffix:bilicdn5.com)'
    'direct(suffix:biliimg.com)'
    'direct(suffix:biliintl.com)'
    'direct(suffix:bilivideo.cn)'
    'direct(suffix:bilivideo.com)'
    'direct(suffix:bilivideo.net)'
    'direct(suffix:bstarstatic.com)'
    'direct(suffix:bstarstatic.net)'
    'direct(suffix:hdslb.com)'
    'direct(suffix:hdslb.org)'
    'direct(p-bstarstatic.akamaized.net)'
    'direct(upos-bstar-mirrorakam.akamaized.net)'
    'direct(upos-bstar1-mirrorakam.akamaized.net)'
    'direct(upos-hz-mirrorakam.akamaized.net)'
)
printf '%s\n' "${bilibili_rules[@]}" > "$rules_path"

awk -v target="$geosite_line" \
    -v managed_begin="$managed_begin_line" \
    -v managed_end="$managed_end_line" \
    -v rules_file="$rules_path" '
    BEGIN {
        while ((getline rule < rules_file) > 0) {
            rules[++rule_count] = rule
        }
        close(rules_file)
    }
    NR == target {
        clean = $0
        sub(/\r$/, "", clean)
        indent = clean
        sub(/-[ \t]*reject\(geosite:cn\).*/, "", indent)
        print indent "# codex-bilibili-cn-exception-begin"
        for (i = 1; i <= rule_count; i++) {
            print indent "- " rules[i]
        }
        print indent "# codex-bilibili-cn-exception-end"
        inserted = 1
    }
    managed_begin > 0 && NR >= managed_begin && NR <= managed_end { next }
    { print $0 }
    END {
        if (!inserted || rule_count == 0) exit 42
    }
' "$config_path" > "$candidate_path"

candidate_geosite_count=$(count_matches "$geosite_pattern" "$candidate_path")
candidate_geoip_count=$(count_matches "$geoip_pattern" "$candidate_path")
if ((candidate_geosite_count != 1 || candidate_geoip_count != 1)); then
    echo "ERROR: candidate did not preserve the China reject pair" >&2
    exit 1
fi

candidate_cn_line=$(grep -En -- "$geosite_pattern" "$candidate_path" | cut -d: -f1)
candidate_geoip_line=$(grep -En -- "$geoip_pattern" "$candidate_path" | cut -d: -f1)
candidate_begin_count=$(count_matches "$managed_begin_pattern" "$candidate_path")
candidate_end_count=$(count_matches "$managed_end_pattern" "$candidate_path")
candidate_begin_line=$(grep -En -- "$managed_begin_pattern" "$candidate_path" | cut -d: -f1)
candidate_end_line=$(grep -En -- "$managed_end_pattern" "$candidate_path" | cut -d: -f1)
if ((candidate_begin_count != 1 || candidate_end_count != 1 || candidate_geoip_line != candidate_cn_line + 1)) ||
   [[ -z "$candidate_begin_line" || -z "$candidate_end_line" ||
      "$candidate_begin_line" -ge "$candidate_end_line" || "$candidate_end_line" -ge "$candidate_cn_line" ]]; then
    echo "ERROR: candidate did not place the Bilibili exceptions before China rejects" >&2
    exit 1
fi

for expected_rule in "${bilibili_rules[@]}"; do
    candidate_rule_count=$(awk -v start="$candidate_begin_line" -v end="$candidate_end_line" -v expected="$expected_rule" '
        NR > start && NR < end {
            rule = $0
            sub(/\r$/, "", rule)
            sub(/^[ \t]*-[ \t]*/, "", rule)
            sub(/[ \t]+$/, "", rule)
            if (rule == expected) count++
        }
        END { print count + 0 }
    ' "$candidate_path")
    if ((candidate_rule_count != 1)); then
        echo "ERROR: candidate is missing or duplicated managed rule: $expected_rule" >&2
        exit 1
    fi
done

if cmp -s -- "$config_path" "$candidate_path"; then
    echo "OK: complete Bilibili exceptions already precede the China reject pair"
    exit 0
fi

echo "FOUND: the generated China reject pair needs ordered Bilibili exceptions"
if [[ "$mode" == "check" ]]; then
    echo "CHECK ONLY: rerun with --apply to add only those exceptions"
    exit 3
fi

service_backend=""
service_was_active=0
restarts_before=""

systemd_health_ok() {
    local active_state sub_state result exec_status
    systemctl is-active --quiet "$service_name" || return 1
    active_state=$(systemctl show "$service_name" -p ActiveState --value 2>/dev/null) || return 1
    sub_state=$(systemctl show "$service_name" -p SubState --value 2>/dev/null) || return 1
    result=$(systemctl show "$service_name" -p Result --value 2>/dev/null) || return 1
    exec_status=$(systemctl show "$service_name" -p ExecMainStatus --value 2>/dev/null) || return 1
    [[ "$active_state" == "active" && ("$sub_state" == "running" || "$sub_state" == "exited") &&
       "$result" == "success" && "$exec_status" == "0" ]]
}

if ((skip_restart == 0)); then
    if command -v systemctl >/dev/null 2>&1 && systemctl cat "${service_name}.service" >/dev/null 2>&1; then
        service_backend="systemd"
        if systemctl is-active --quiet "$service_name"; then
            service_was_active=1
            restarts_before=$(systemctl show "$service_name" -p NRestarts --value 2>/dev/null || true)
        fi
    elif command -v service >/dev/null 2>&1 && [[ -x "/etc/init.d/$service_name" ]]; then
        service_backend="service"
        if service "$service_name" status >/dev/null 2>&1; then
            service_was_active=1
        fi
    else
        echo "ERROR: V2bX service definition was not found; use --skip-restart only for manual validation" >&2
        exit 1
    fi
fi

timestamp=$(date -u +%Y%m%dT%H%M%SZ)
backup_path="${config_path}.bak-bilibili-${timestamp}-$$"
cp -a -- "$config_path" "$backup_path"

stage_dir=$(mktemp -d "${config_dir}/.hy2-bilibili-repair.XXXXXX")
replacement_path="$stage_dir/hy2config.yaml"
cp -a -- "$config_path" "$replacement_path"
cat "$candidate_path" > "$replacement_path"
cmp -s -- "$candidate_path" "$replacement_path"

changed=0
rollback_config() {
    local restore_dir restore_path restore_ok=0 service_ok=0
    restore_dir=$(mktemp -d "${config_dir}/.hy2-bilibili-restore.XXXXXX") || return 1
    restore_path="$restore_dir/hy2config.yaml"
    if cp -a -- "$backup_path" "$restore_path" &&
       mv -f -- "$restore_path" "$config_path" &&
       cmp -s -- "$backup_path" "$config_path"; then
        restore_ok=1
    fi
    rmdir -- "$restore_dir" 2>/dev/null || true

    if ((service_was_active == 0)); then
        service_ok=1
    elif [[ "$service_backend" == "systemd" ]]; then
        if systemctl restart "$service_name" && sleep 2 && systemd_health_ok; then
            service_ok=1
        fi
    elif [[ "$service_backend" == "service" ]]; then
        if service "$service_name" restart && sleep 2 && service "$service_name" status >/dev/null 2>&1; then
            service_ok=1
        fi
    fi

    if ((restore_ok == 0)); then
        echo "CRITICAL: automatic config restore failed" >&2
        echo "Restore manually: cp -a '$backup_path' '$config_path'" >&2
    fi
    if ((service_ok == 0)); then
        echo "CRITICAL: original config was restored but $service_name did not recover" >&2
    fi
    ((restore_ok == 1 && service_ok == 1))
}

handle_failure() {
    local status="$1"
    trap - ERR INT TERM
    set +e
    if ((changed)); then
        echo "ERROR: repair failed; restoring the original configuration" >&2
        rollback_config || status=1
    fi
    exit "$status"
}
trap 'handle_failure $?' ERR
trap 'handle_failure 130' INT
trap 'handle_failure 143' TERM

trap '' INT TERM
if mv -f -- "$replacement_path" "$config_path"; then
    changed=1
else
    trap 'handle_failure 130' INT
    trap 'handle_failure 143' TERM
    echo "ERROR: atomic config replacement failed; original config remains in place" >&2
    exit 1
fi
trap 'handle_failure 130' INT
trap 'handle_failure 143' TERM
if rmdir -- "$stage_dir" 2>/dev/null; then
    stage_dir=""
fi

if ((skip_restart)); then
    echo "NOTICE: service restart skipped by request"
elif ((service_was_active == 0)); then
    echo "NOTICE: $service_name was inactive and remains inactive"
elif [[ "$service_backend" == "systemd" ]]; then
    if ! systemctl restart "$service_name"; then
        echo "ERROR: systemd restart failed" >&2
        false
    fi
    for health_sample in 1 2; do
        sleep 2
        if ! systemd_health_ok; then
            echo "ERROR: service health check $health_sample failed after restart" >&2
            false
        fi
        restarts_after=$(systemctl show "$service_name" -p NRestarts --value 2>/dev/null || true)
        if [[ "$restarts_before" =~ ^[0-9]+$ && "$restarts_after" =~ ^[0-9]+$ ]] && ((restarts_after > restarts_before)); then
            echo "ERROR: service entered an automatic restart cycle" >&2
            false
        fi
    done
else
    if ! service "$service_name" restart; then
        echo "ERROR: service restart failed" >&2
        false
    fi
    for health_sample in 1 2; do
        sleep 2
        if ! service "$service_name" status >/dev/null 2>&1; then
            echo "ERROR: service health check $health_sample failed after restart" >&2
            false
        fi
    done
fi

changed=0
trap - ERR INT TERM
echo "REPAIRED: added only Bilibili exceptions; China reject rules remain enabled"
echo "BACKUP: $backup_path"
if ((service_was_active)); then
    echo "SERVICE: $service_name restart and health check passed"
fi
